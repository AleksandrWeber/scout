export const formatTranslation = (
  template: string,
  values?: Record<string, string | number>
): string => {
  if (!values) {
    return template;
  }

  return Object.entries(values).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    template
  );
};
